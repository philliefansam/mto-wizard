export const FORMICA_LAMINATES = FORMICA_CATALOG.map((item) => item.label);

/**
 * Filter Formica catalog items matching a search query.
 * Matches against pattern number, design name, or full label.
 * @param {string} query
 * @param {number} limit
 * @returns {Array<{brand: string, name: string, number: string, label: string}>}
 */
export function searchFormica(query, limit = 12) {
  if (!query || typeof query !== 'string') return [];
  const q = query.trim().toLowerCase();
  if (q.length === 0) return [];

  if (q === 'formica' || q === 'formica ') {
    return FORMICA_CATALOG.slice(0, limit);
  }

  const strippedQ = q.replace(/^formica\s+/i, '').trim();
  const searchQ = strippedQ.length > 0 ? strippedQ : q;
  const tokens = searchQ.split(/\s+/);

  const matches = FORMICA_CATALOG.filter((item) => {
    const hay = `${item.label} ${item.name} ${item.number}`.toLowerCase();
    return tokens.every((token) => {
      const cleanToken = token.replace(/[^a-z0-9]/g, '');
      const cleanHay = hay.replace(/[^a-z0-9]/g, '');
      return hay.includes(token) || (cleanToken.length >= 2 && cleanHay.includes(cleanToken));
    });
  });

  // Relevance ranking
  matches.sort((a, b) => {
    const aName = a.name.toLowerCase();
    const bName = b.name.toLowerCase();
    const aNum = a.number.toLowerCase();
    const bNum = b.number.toLowerCase();

    // 1. Exact match on name or number
    const aExact = aName === searchQ || aNum === searchQ;
    const bExact = bName === searchQ || bNum === searchQ;
    if (aExact && !bExact) return -1;
    if (!aExact && bExact) return 1;

    // 2. Starts with search query
    const aPrefix = aName.startsWith(searchQ) || aNum.startsWith(searchQ);
    const bPrefix = bName.startsWith(searchQ) || bNum.startsWith(searchQ);
    if (aPrefix && !bPrefix) return -1;
    if (!aPrefix && bPrefix) return 1;

    // 3. Word boundary in name
    const aWord = new RegExp(`\\b${searchQ}`, 'i').test(a.name);
    const bWord = new RegExp(`\\b${searchQ}`, 'i').test(b.name);
    if (aWord && !bWord) return -1;
    if (!aWord && bWord) return 1;

    return a.name.localeCompare(b.name);
  });

  return matches.slice(0, limit);
}

